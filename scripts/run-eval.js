// Runs the evaluation suite and writes docs/EVALUATION_REPORT.md and
// docs/evaluation-latest.json from the actual results.
import { writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { openDb } from '../server/db.js'
import { runEvaluation } from '../server/evaluation.js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const db = openDb(':memory:')
const r = await runEvaluation(db)
mkdirSync(join(root, 'docs'), { recursive: true })
writeFileSync(join(root, 'docs', 'evaluation-latest.json'), JSON.stringify(r, null, 2))

const per = r.summary.perConfig
const cols = Object.keys(per)
const f = (x) => `${Object.values(x)[0]}/${x.total}`
const row = (label, fn) => `| ${label} | ${cols.map((c) => fn(per[c])).join(' | ')} |`
const firsts = r.results.filter((x) => x.repeat === 0)
const ids = [...new Set(firsts.map((x) => x.caseId))]
const lines = [
  '# Evaluation report (generated)',
  '',
  `Generated by \`npm run eval\` at ${r.finishedAt}. Code revision \`${r.codeRevision}\`. Suite \`${r.suiteVersion}\` (hash \`${r.suiteHash.slice(7, 19)}\`), criteria hash \`${r.criteriaHash.slice(7, 19)}\`.`,
  '',
  '**Read this first.** These are synthetic engineering checks of workflow controls. The `fixture-sim-v1` configuration is a deterministic program written by the same author as the cases; its "draft quality" results show that the checks and gates work on known inputs, not that any AI model performs well. No live model was called. No human reviewer took part: semantic support was labeled by a scripted reviewer. A small passing suite is prototype evidence only.',
  '',
  `**Prototype demo gate:** ${r.summary.readinessGate.demoReady ? 'PASS' : 'BLOCKED'} (unsafe outcomes: ${r.summary.readinessGate.unsafeOutcomes}; unauthorized actions allowed: ${r.summary.readinessGate.unauthorizedActionsAllowed}). ${r.summary.readinessGate.label}`,
  '',
  '## Summary by configuration',
  '',
  `| Measure | ${cols.join(' | ')} |`,
  `|---|${cols.map(() => '---').join('|')}|`,
  row('Dev cases passed', (p) => `${p.dev.passed}/${p.dev.cases}`),
  row('Held-out cases passed', (p) => `${p.heldout.passed}/${p.heldout.cases}${p.heldout.failedKnownLimitation ? ` (${p.heldout.failedKnownLimitation} declared limitation)` : ''}`),
  row('Control expectations met', (p) => f(p.controlExpectations)),
  row('Draft-quality expectations met', (p) => f(p.draftQualityExpectations)),
  row('Must-block attempts that were allowed (unsafe)', (p) => `${p.unsafeOutcomes} of ${p.mustBlockAttempts}`),
  row('Requirement coverage, first draft (sum over cases)', (p) => f(p.requirementCoverage)),
  row('Invalid citations, first draft', (p) => `${p.invalidCitations.invalid}/${p.invalidCitations.total}`),
  row('Record gaps disclosed in the draft itself', (p) => f(p.recordGapsDisclosedInDraft)),
  row('Record conflicts disclosed in the draft itself', (p) => f(p.recordConflictsDisclosedInDraft)),
  row('Generation latency, median / max', (p) => `${p.generationLatencyMs.median} / ${p.generationLatencyMs.max} ms (local, no model call)`),
  row('Cost', (p) => p.costUsd),
  row('Repeats per case', (p) => `${p.repeats.perCase} (identical: ${p.repeats.identicalAcrossRepeats})`),
  row('Reviewer-adjudicated unsupported claims', (p) => p.reviewerAdjudicatedUnsupportedClaims),
  '',
  'Denominators: case counts are distinct cases (repeats excluded). Citation and coverage totals are summed across first-repeat cases. Invalid citations for the simulated model are dominated by the one seeded fabricated step present in every fixture run.',
  '',
  '## Cases',
  '',
  `| Case | Split | Title | ${cols.join(' | ')} |`,
  `|---|---|---|${cols.map(() => '---').join('|')}|`,
  ...ids.map((id) => {
    const rs = firsts.filter((x) => x.caseId === id)
    const cell = (c) => {
      const x = rs.find((y) => y.configId === c)
      if (!x) return 'n/a'
      const fails = x.expectations.filter((e) => !e.pass).map((e) => `${e.type}: ${JSON.stringify(e.observed)}`)
      return `${x.outcome}${fails.length ? ` (${fails.join('; ').replace(/\|/g, '/')})` : ''}`
    }
    return `| ${id} | ${rs[0].split} | ${rs[0].title} | ${cols.map(cell).join(' | ')} |`
  }),
  '',
  'Outcome labels: `PASS`; `FAIL_CONTROL` (a gate did not hold; none observed); `FAIL_QUALITY` (the draft did not disclose something the checks found; expected for the template baseline); `FAIL_KNOWN_LIMITATION` (declared in `fixtures/eval/criteria.json` before the run).',
  '',
  '## What this does and does not show',
  '',
  '- Shows: on these fixtures, missing and conflicting evidence blocked acceptance; stale, revoked, superseded and unauthorized decisions were rejected; retried operations did not duplicate; restricted sources stayed out of model context; a provider failure was explicit.',
  '- Shows (H08): mechanical citation checks cannot tell a real quote attached to the wrong claim from a supporting one. Only the reviewer judgment caught it.',
  '- Does not show: real-model draft quality, reviewer effort, time savings, operational effectiveness, or any statistical reliability. Crash-after-commit recovery and restart persistence are covered by the process-level tests in `test/process.test.js`, not by these cases.',
  ''
]
writeFileSync(join(root, 'docs', 'EVALUATION_REPORT.md'), lines.join('\n'))
console.log(`Gate: ${r.summary.readinessGate.demoReady ? 'PASS' : 'BLOCKED'}; wrote docs/EVALUATION_REPORT.md`)
for (const c of cols) console.log(`${c}: dev ${per[c].dev.passed}/${per[c].dev.cases}, held-out ${per[c].heldout.passed}/${per[c].heldout.cases}, unsafe ${per[c].unsafeOutcomes}`)
