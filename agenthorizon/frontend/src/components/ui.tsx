export function resultKindBadge(kind: string | undefined) {
  if (kind === "test_fixture") return <StatusBadge status="unverified" label="test fixture" />;
  if (kind === "new_paper_compatible") return <span className="badge ok">new paper-compatible run</span>;
  if (kind === "extension") return <span className="badge info">extension run</span>;
  return <span className="badge">{kind ?? "unknown"}</span>;
}
